/**
 * AI Library panel (Phase 6, SPEC O — O-AI-LIBRARY, O-AI-GENERATE,
 * O-AI-MUSIC, O-AI-CLIPS, O-AI-IMAGES, O-AI-VOICES).
 * 11th left tab ("AI Tools"): five sub-tabs — Generate, Music, Clips,
 * Images, Voices. All content is Vidora Original (generated by
 * generation/), local files, no sign-in, no credits.
 * Missing files (text-only checkout) show an honest note; music rows
 * still work via in-browser Web Audio synthesis of the same pattern.
 */

type SubTab = 'clips' | 'generate' | 'images' | 'music' | 'voices';

function swatchFor(id: string): string {
  const palette = ['#7C3AED', '#06B6D4', '#F59E0B', '#10B981', '#EF4444', '#EC4899'];
  let h = 0;
  for (let i = 0; i < id.length; i += 1) h = (h * 31 + id.charCodeAt(i)) % palette.length;
  return palette[h];
}

const chipCls = (active: boolean) =>
  `rounded-full border px-2 py-1 text-[11px] ${active ? 'border-violet-500 bg-violet-600/20 text-violet-200' : 'border-zinc-700 text-zinc-300 hover:bg-zinc-800'}`;
const addBtnCls =
  'rounded-md border border-zinc-700 px-2 py-1 text-[11px] text-zinc-200 hover:bg-zinc-800 disabled:opacity-40';
const playBtnCls = 'rounded-md border border-zinc-700 px-2 py-1 text-[11px] text-zinc-200 hover:bg-zinc-800';

export default function AILibraryPanel() {
  const addMediaItem = useProjectStore((s) => s.addMediaItem);
  const addAudioClip = useProjectStore((s) => s.addAudioClip);
  const addAiMediaClip = useProjectStore((s) => s.addAiMediaClip);
  const addTtsNarration = useProjectStore((s) => s.addTtsNarration);
  const generateCaptionsFromTranscript = useProjectStore((s) => s.generateCaptionsFromTranscript);

  const [subTab, setSubTab] = useState<SubTab>('music');
  const [query, setQuery] = useState('');
  const [category, setCategory] = useState('All');
  const [playingId, setPlayingId] = useState<string | null>(null);
  const [busyId, setBusyId] = useState<string | null>(null);
  const [missing, setMissing] = useState<{ clips: boolean; images: boolean; music: boolean; sfx: boolean } | null>(null);
  const [notice, setNotice] = useState('');

  useEffect(() => {
    let alive = true;
    void aiLibraryInstalled().then((r) => {
      if (alive) setMissing(r);
    });
    return () => {
      alive = false;
      stopPreview();
    };
  }, []);

  useEffect(() => {
    setCategory('All');
    setQuery('');
    setNotice('');
  }, [subTab]);

  const addAudioEntry = async (entry: AiMusicEntry | AiSfxEntry, kind: 'music' | 'sfx') => {
    setBusyId(entry.id);
    setNotice('');
    try {
      const installed = await aiFileAvailable(entry.file);
      let item: MediaItem;
      if (installed) {
        item = {
          createdAt: new Date().toISOString(),
          duration: entry.duration,
          folderId: 'folder-all',
          id: newId('media'),
          kind: 'audio',
          mime: 'audio/mpeg',
          name: entry.name,
          peakLevel: kind === 'music' ? (entry as AiMusicEntry).peak : undefined,
          peaks: entry.peaks.map((p) => Math.min(1, Math.max(0, p))),
          size: entry.size,
          src: entry.file,
        };
      } else if (kind === 'music') {
        // In-browser synthesis fallback (same pattern as the MP3).
        const rendered = await renderAiTrackEntry(entry as AiMusicEntry);
        item = {
          createdAt: new Date().toISOString(),
          duration: rendered.duration,
          folderId: 'folder-all',
          id: newId('media'),
          kind: 'audio',
          mime: 'audio/wav',
          name: `${entry.name} (synthesised)`,
          peakLevel: rendered.peakLevel,
          peaks: rendered.peaks,
          size: rendered.blob.size,
          src: rendered.url,
        };
        setNotice(`"${entry.name}" was rendered in the browser — the MP3 file is not in this install (full library ships in the Drive release).`);
      } else {
        setNotice(`"${entry.name}" needs its MP3 file — the full AI library ships in the Drive release.`);
        return;
      }
      addMediaItem(item);
      addAudioClip(item.id);
    } finally {
      setBusyId(null);
    }
  };

  const addVideoEntry = async (entry: AiClipEntry) => {
    setBusyId(entry.id);
    setNotice('');
    try {
      const installed = await aiFileAvailable(entry.file);
      if (!installed) {
        setNotice(`"${entry.name}" needs its MP4 file — the full AI library ships in the Drive release. The Generate tab can still make a short clip in the browser.`);
        return;
      }
      const item: MediaItem = {
        createdAt: new Date().toISOString(),
        duration: entry.duration,
        folderId: 'folder-all',
        height: entry.height,
        id: newId('media'),
        kind: 'video',
        mime: 'video/mp4',
        name: entry.name,
        size: entry.size,
        src: entry.file,
        thumbnail: entry.poster,
        width: entry.width,
      };
      addMediaItem(item);
      addAiMediaClip(item.id);
    } finally {
      setBusyId(null);
    }
  };

  const addImageEntry = async (entry: AiImageEntry) => {
    setBusyId(entry.id);
    setNotice('');
    try {
      const installed = await aiFileAvailable(entry.file);
      if (!installed) {
        setNotice(`"${entry.name}" needs its PNG file — the full AI library ships in the Drive release. The Generate tab can still make an image in the browser.`);
        return;
      }
      const item: MediaItem = {
        createdAt: new Date().toISOString(),
        duration: 5,
        folderId: 'folder-all',
        height: entry.height,
        id: newId('media'),
        kind: 'image',
        mime: 'image/png',
        name: entry.name,
        size: entry.size,
        src: entry.file,
        thumbnail: entry.file,
        width: entry.width,
      };
      addMediaItem(item);
      addAiMediaClip(item.id);
    } finally {
      setBusyId(null);
    }
  };

  const toggleAudioPreview = (id: string, src: string) => {
    const started = playPreview(src);
    setPlayingId(started ? id : null);
  };

  const musicRows = useMemo(
    () =>
      AI_MUSIC_TRACKS.filter(
        (t) => (category === 'All' || t.style === category) && aiMatches([t.name, t.style, t.mood, ...t.tags], query),
      ),
    [category, query],
  );
  const sfxRows = useMemo(
    () =>
      AI_SFX.filter(
        (s) => (category === 'All' || s.family === category) && aiMatches([s.name, s.family, ...s.tags], query),
      ),
    [category, query],
  );
  const clipCards = useMemo(
    () =>
      AI_CLIPS.filter(
        (c) => (category === 'All' || c.scene === category) && aiMatches([c.name, c.scene, c.motion, ...c.tags], query),
      ),
    [category, query],
  );
  const imageCards = useMemo(
    () =>
      AI_IMAGES.filter(
        (im) =>
          (category === 'All' ||
            (category === 'Textures' && im.kind === 'texture') ||
            (category === 'Frames' && im.kind === 'frame') ||
            (category === 'Stickers' && im.kind === 'sticker')) &&
          aiMatches([im.name, im.design, im.kind, ...im.tags], query),
      ),
    [category, query],
  );

  const categories =
    subTab === 'music'
      ? ['All', ...AI_MUSIC_STYLES]
      : subTab === 'clips'
        ? ['All', ...AI_CLIP_SCENES]
        : subTab === 'images'
          ? ['All', 'Textures', 'Frames', 'Stickers']
          : ['All', ...AI_SFX_FAMILIES];

  const missingNote =
    missing && (!missing.music || !missing.clips || !missing.images || !missing.sfx)
      ? 'Some library files are not in this install (text-only checkout) — the full AI library ships in the Drive release. Music rows still work: they render in the browser.'
      : '';

  return (
    <aside className="flex w-72 shrink-0 flex-col overflow-hidden border-r border-zinc-800 bg-zinc-950 text-zinc-100" aria-label="AI Library">
      <div className="border-b border-zinc-800 p-3">
        <h2 className="text-sm font-semibold">AI Library</h2>
        <p className="mt-1 text-[11px] leading-relaxed text-zinc-500">
          Vidora Originals — generated locally, no sign-in, no credits. {AI_MUSIC_TRACKS.length} tracks · {AI_CLIPS.length} clips · {AI_IMAGES.length} images · {AI_VOICES.length} voices.
        </p>
        <div className="mt-2 flex flex-wrap gap-1" role="tablist" aria-label="AI Library sections">
          {(['generate', 'music', 'clips', 'images', 'voices'] as SubTab[]).map((t) => (
            <button key={t} type="button" role="tab" aria-selected={subTab === t} onClick={() => setSubTab(t)} className={chipCls(subTab === t)}>
              {t === 'generate' ? 'Generate' : t === 'music' ? 'Music' : t === 'clips' ? 'Clips' : t === 'images' ? 'Images' : 'Voices'}
            </button>
          ))}
        </div>
        {subTab !== 'generate' && subTab !== 'voices' && (
          <>
            <input
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              placeholder="Search AI library…"
              aria-label="Search AI library"
              className="mt-2 w-full rounded-md border border-zinc-700 bg-zinc-900 px-2 py-1.5 text-xs text-zinc-100"
            />
            <div className="mt-2 flex flex-wrap gap-1">
              {categories.map((c) => (
                <button key={c} type="button" onClick={() => setCategory(c)} className={chipCls(category === c)}>
                  {c}
                </button>
              ))}
            </div>
          </>
        )}
        {missingNote && <p className="mt-2 rounded-md border border-amber-700/60 bg-amber-950/40 p-2 text-[11px] leading-relaxed text-amber-200">{missingNote}</p>}
        {notice && <p className="mt-2 rounded-md border border-zinc-700 bg-zinc-900 p-2 text-[11px] leading-relaxed text-zinc-300">{notice}</p>}
      </div>

      <div className="flex-1 overflow-y-auto p-3">
        {subTab === 'generate' && (
          <GenerateSection
            onAddAudio={(item) => {
              addMediaItem(item);
              addAudioClip(item.id);
            }}
            onAddVideo={(item) => {
              addMediaItem(item);
              addAiMediaClip(item.id);
            }}
            onAddDialogue={(imageUrl, text, voiceName, rate, pitch) => {
              if (imageUrl) {
                const item: MediaItem = {
                  createdAt: new Date().toISOString(),
                  duration: 5,
                  folderId: 'folder-all',
                  height: 720,
                  id: newId('media'),
                  kind: 'image',
                  mime: 'image/png',
                  name: 'AI dialogue scene',
                  size: 0,
                  src: imageUrl,
                  thumbnail: imageUrl,
                  width: 1280,
                };
                addMediaItem(item);
                addAiMediaClip(item.id);
              }
              generateCaptionsFromTranscript(text, 'en');
              addTtsNarration(text, voiceName, rate, pitch);
            }}
          />
        )}

        {subTab === 'music' && (
          <>
            <SectionHeading title="AI tracks" count={musicRows.length} />
            {musicRows.length === 0 && <Empty text="No AI tracks match this search." />}
            <ul className="space-y-2">
              {musicRows.map((t) => (
                <li key={t.id} className="rounded-lg border border-zinc-800 bg-zinc-900 p-2">
                  <div className="flex items-center gap-2">
                    <span className="h-8 w-8 shrink-0 rounded" style={{ backgroundColor: swatchFor(t.id) }} aria-hidden />
                    <div className="min-w-0 flex-1">
                      <p className="truncate text-xs font-medium" title={t.name}>{t.name}</p>
                      <p className="text-[11px] text-zinc-500">
                        {t.style} · {t.bpm} BPM · {t.key} · {formatDuration(t.duration)}
                        {t.loopable ? ' · Loop' : ''}
                      </p>
                    </div>
                  </div>
                  <div className="mt-1.5 flex gap-1.5">
                    <button type="button" className={playBtnCls} onClick={() => toggleAudioPreview(t.id, t.file)}>
                      {playingId === t.id ? '⏸ Pause' : '▶ Play'}
                    </button>
                    <button type="button" className={addBtnCls} disabled={busyId === t.id} onClick={() => void addAudioEntry(t, 'music')}>
                      {busyId === t.id ? 'Adding…' : '+ Add'}
                    </button>
                  </div>
                </li>
              ))}
            </ul>
            <SectionHeading title="AI sound effects" count={sfxRows.length} />
            {sfxRows.length === 0 && <Empty text="No AI sound effects match this search." />}
            <ul className="space-y-2">
              {sfxRows.map((s) => (
                <li key={s.id} className="rounded-lg border border-zinc-800 bg-zinc-900 p-2">
                  <div className="flex items-center gap-2">
                    <span className="h-8 w-8 shrink-0 rounded" style={{ backgroundColor: swatchFor(s.id) }} aria-hidden />
                    <div className="min-w-0 flex-1">
                      <p className="truncate text-xs font-medium" title={s.name}>{s.name}</p>
                      <p className="text-[11px] text-zinc-500">{s.family} · {formatDuration(s.duration)}</p>
                    </div>
                  </div>
                  <div className="mt-1.5 flex gap-1.5">
                    <button type="button" className={playBtnCls} onClick={() => toggleAudioPreview(s.id, s.file)}>
                      {playingId === s.id ? '⏸ Pause' : '▶ Play'}
                    </button>
                    <button type="button" className={addBtnCls} disabled={busyId === s.id} onClick={() => void addAudioEntry(s, 'sfx')}>
                      {busyId === s.id ? 'Adding…' : '+ Add'}
                    </button>
                  </div>
                </li>
              ))}
            </ul>
          </>
        )}

        {subTab === 'clips' && (
          <>
            <SectionHeading title="AI clips" count={clipCards.length} />
            {clipCards.length === 0 && <Empty text="No AI clips match this search." />}
            <ul className="grid grid-cols-2 gap-2">
              {clipCards.map((c) => (
                <ClipCard key={c.id} entry={c} busy={busyId === c.id} onAdd={() => void addVideoEntry(c)} />
              ))}
            </ul>
          </>
        )}

        {subTab === 'images' && (
          <>
            <SectionHeading title="AI images" count={imageCards.length} />
            {imageCards.length === 0 && <Empty text="No AI images match this search." />}
            <ul className="grid grid-cols-2 gap-2">
              {imageCards.map((im) => (
                <li key={im.id} className="rounded-lg border border-zinc-800 bg-zinc-900 p-2">
                  <img src={im.file} alt={im.name} className="h-20 w-full rounded object-cover" loading="lazy" />
                  <p className="mt-1.5 truncate text-xs font-medium" title={im.name}>{im.name}</p>
                  <p className="text-[11px] text-zinc-500">
                    {im.kind === 'texture' ? 'Texture' : im.kind === 'frame' ? 'Frame' : 'Sticker'} · {im.width}×{im.height}
                  </p>
                  <button type="button" className={`${addBtnCls} mt-1.5 w-full`} disabled={busyId === im.id} onClick={() => void addImageEntry(im)}>
                    {busyId === im.id ? 'Adding…' : '+ Add'}
                  </button>
                </li>
              ))}
            </ul>
          </>
        )}

        {subTab === 'voices' && <VoicesSection />}
      </div>
    </aside>
  );
}

function SectionHeading({ count, title }: { count: number; title: string }) {
  return (
    <h3 className="mb-2 mt-3 text-xs font-semibold text-zinc-300 first:mt-0">
      {title} <span className="font-normal text-zinc-500">({count})</span>
    </h3>
  );
}

function Empty({ text }: { text: string }) {
  return <p className="py-2 text-xs leading-relaxed text-zinc-500">{text}</p>;
}

function ClipCard({ busy, entry, onAdd }: { busy: boolean; entry: AiClipEntry; onAdd: () => void }) {
  const [previewing, setPreviewing] = useState(false);
  return (
    <li className="rounded-lg border border-zinc-800 bg-zinc-900 p-2">
      {previewing ? (
        <video src={entry.file} className="h-20 w-full rounded object-cover" autoPlay loop muted controls={false} />
      ) : (
        <button type="button" onClick={() => setPreviewing(true)} aria-label={`Preview ${entry.name}`} className="block w-full">
          <img src={entry.poster} alt={entry.name} className="h-20 w-full rounded object-cover" loading="lazy" />
        </button>
      )}
      <p className="mt-1.5 truncate text-xs font-medium" title={entry.name}>{entry.name}</p>
      <p className="text-[11px] text-zinc-500">{entry.scene} · {formatDuration(entry.duration)} · 1080p</p>
      <div className="mt-1.5 flex gap-1.5">
        <button type="button" className={playBtnCls} onClick={() => setPreviewing((v) => !v)}>
          {previewing ? '■ Stop' : '▶ Play'}
        </button>
        <button type="button" className={addBtnCls} disabled={busy} onClick={onAdd}>
          {busy ? 'Adding…' : '+ Add'}
        </button>
      </div>
    </li>
  );
}

function VoicesSection() {
  const addTtsNarration = useProjectStore((s) => s.addTtsNarration);
  const [lang, setLang] = useState('English');
  const [voices, setVoices] = useState<TtsVoiceInfo[]>([]);
  const [narration, setNarration] = useState('');
  const [speakingId, setSpeakingId] = useState<string | null>(null);
  const [note, setNote] = useState('');

  useEffect(() => {
    if (typeof window === 'undefined' || !('speechSynthesis' in window)) return;
    const load = () => setVoices(voiceInfos(window.speechSynthesis.getVoices().map((v) => ({ lang: v.lang, localService: v.localService, name: v.name }))));
    load();
    window.speechSynthesis.addEventListener('voiceschanged', load);
    return () => window.speechSynthesis.removeEventListener('voiceschanged', load);
  }, []);

  const rows = AI_VOICES.filter((v) => v.lang === lang);
  const preview = (preset: AiVoicePreset) => {
    const name = resolveAiVoice(voices, preset);
    if (!name) {
      setNote(`No ${preset.lang} voice is installed on this device — the narration clip will still be created and speaks when a voice is available.`);
      return;
    }
    setNote('');
    if (previewAiVoice(preset, name)) setSpeakingId(preset.id);
    else setNote('Speech is not available in this browser.');
  };
  const addNarration = (preset: AiVoicePreset) => {
    const text = narration.trim() || preset.sample;
    const name = resolveAiVoice(voices, preset);
    addTtsNarration(text, name, preset.rate, preset.pitch);
    setNarration('');
  };

  return (
    <>
      <p className="text-[11px] leading-relaxed text-zinc-500">
        16 voice presets — 4 languages × 4 roles. Browser voices; quality depends on this device. Rendered voice audio in export arrives in Phase 7.
      </p>
      <div className="mt-2 flex flex-wrap gap-1">
        {AI_VOICE_LANGUAGES.map((l) => (
          <button key={l} type="button" onClick={() => setLang(l)} className={chipCls(lang === l)}>
            {l}
          </button>
        ))}
      </div>
      <input
        value={narration}
        onChange={(e) => setNarration(e.target.value)}
        placeholder="Narration text (empty = sample sentence)…"
        aria-label="Narration text"
        className="mt-2 w-full rounded-md border border-zinc-700 bg-zinc-900 px-2 py-1.5 text-xs text-zinc-100"
      />
      {note && <p className="mt-2 rounded-md border border-zinc-700 bg-zinc-900 p-2 text-[11px] leading-relaxed text-zinc-300">{note}</p>}
      <ul className="mt-2 space-y-2">
        {rows.map((v) => (
          <li key={v.id} className="rounded-lg border border-zinc-800 bg-zinc-900 p-2">
            <p className="text-xs font-medium">{v.name}</p>
            <p className="mt-0.5 text-[11px] italic leading-relaxed text-zinc-400">“{v.sample}”</p>
            <p className="text-[11px] text-zinc-500">Pitch {v.pitch} · Rate {v.rate}</p>
            <div className="mt-1.5 flex gap-1.5">
              <button type="button" className={playBtnCls} onClick={() => preview(v)}>
                {speakingId === v.id ? '🔊 Speaking…' : '▶ Preview'}
              </button>
              <button type="button" className={addBtnCls} onClick={() => addNarration(v)}>
                + Add narration
              </button>
            </div>
          </li>
        ))}
      </ul>
    </>
  );
}

function GenerateSection({
  onAddAudio,
  onAddDialogue,
  onAddVideo,
}: {
  onAddAudio: (item: MediaItem) => void;
  onAddDialogue: (imageUrl: string | null, text: string, voiceName: string, rate: number, pitch: number) => void;
  onAddVideo: (item: MediaItem) => void;
}) {
  const [prompt, setPrompt] = useState('');
  const [type, setType] = useState<AiGenerateType>('image');
  const [count, setCount] = useState(3);
  const [generating, setGenerating] = useState(false);
  const [progress, setProgress] = useState('');
  const [error, setError] = useState('');
  const [results, setResults] = useState<
    { kind: AiGenerateType; label: string; src: string; blob?: Blob; duration?: number }[]
  >([]);
  const [addedIds, setAddedIds] = useState<Set<string>>(new Set());

  const model = AI_GENERATE_TYPES.find((t) => t.id === type)?.model ?? 'Vidora Canvas';

  const run = async () => {
    if (!prompt.trim() || generating) return;
    setGenerating(true);
    setError('');
    setResults([]);
    setAddedIds(new Set());
    try {
      const out: { kind: AiGenerateType; label: string; src: string; blob?: Blob; duration?: number }[] = [];
      if (type === 'music') {
        setProgress(`Generating ${count} track${count > 1 ? 's' : ''}…`);
        const tracks = await generateMusic(prompt, count);
        for (const track of tracks) {
          out.push({ blob: track.blob, duration: track.duration, kind: 'music', label: track.name, src: track.url });
        }
      } else if (type === 'image') {
        for (let i = 0; i < count; i += 1) {
          setProgress(`Generating ${i + 1} of ${count}…`);
          const src = generateImage(prompt, i);
          if (src) out.push({ kind: 'image', label: `AI image ${i + 1} — "${prompt.trim().slice(0, 24)}"`, src });
        }
      } else if (type === 'video') {
        for (let i = 0; i < count; i += 1) {
          setProgress(`Generating ${i + 1} of ${count}… (3 s each)`);
          const clip = await generateClip(prompt, i);
          if (clip) out.push({ blob: clip.blob, duration: clip.duration, kind: 'video', label: `AI clip ${i + 1} — "${prompt.trim().slice(0, 24)}"`, src: clip.url });
        }
      } else {
        const scene = dialogueSceneFor(prompt);
        setProgress('Building dialogue scene…');
        out.push({ kind: 'dialogue', label: `Dialogue scene — "${prompt.trim().slice(0, 24)}"`, src: scene.image ?? '' });
        setResults(out);
        setProgress('');
        setGenerating(false);
        return;
      }
      if (out.length === 0) setError('Nothing was generated — this browser may not support the generator for this type.');
      setResults(out);
    } catch (e) {
      setError(`Generation failed: ${e instanceof Error ? e.message : 'unknown error'}`);
    } finally {
      setProgress('');
      setGenerating(false);
    }
  };

  const addResult = (r: { kind: AiGenerateType; label: string; src: string; blob?: Blob; duration?: number }) => {
    const key = `${r.kind}:${r.label}`;
    if (addedIds.has(key)) return;
    if (r.kind === 'music' && r.blob) {
      onAddAudio({
        createdAt: new Date().toISOString(),
        duration: r.duration ?? 15,
        folderId: 'folder-all',
        id: newId('media'),
        kind: 'audio',
        mime: 'audio/wav',
        name: r.label,
        size: r.blob.size,
        src: r.src,
      });
    } else if (r.kind === 'image') {
      onAddVideo({
        createdAt: new Date().toISOString(),
        duration: 5,
        folderId: 'folder-all',
        height: 720,
        id: newId('media'),
        kind: 'image',
        mime: 'image/png',
        name: r.label,
        size: 0,
        src: r.src,
        thumbnail: r.src,
        width: 1280,
      });
    } else if (r.kind === 'video' && r.blob) {
      onAddVideo({
        createdAt: new Date().toISOString(),
        duration: r.duration ?? 3,
        folderId: 'folder-all',
        height: 720,
        id: newId('media'),
        kind: 'video',
        mime: 'video/webm',
        name: r.label,
        size: r.blob.size,
        src: r.src,
        width: 1280,
      });
    } else if (r.kind === 'dialogue') {
      const scene = dialogueSceneFor(prompt);
      const text = scene.lines.join(' ');
      onAddDialogue(r.src || null, text, scene.voice.name, scene.voice.rate, scene.voice.pitch);
    }
    setAddedIds((prev) => new Set(prev).add(key));
  };

  return (
    <>
      <p className="text-[11px] leading-relaxed text-zinc-500">
        Generated locally in your browser — no sign-in, no credits. Same prompt always makes the same result.
      </p>
      <textarea
        value={prompt}
        onChange={(e) => setPrompt(e.target.value)}
        placeholder="Describe what to generate…"
        aria-label="Generation prompt"
        rows={3}
        className="mt-2 w-full rounded-md border border-zinc-700 bg-zinc-900 px-2 py-1.5 text-xs text-zinc-100"
      />
      <div className="mt-2 flex flex-wrap gap-1">
        {AI_GENERATE_TYPES.map((t) => (
          <button key={t.id} type="button" onClick={() => setType(t.id)} className={chipCls(type === t.id)}>
            {t.label}
          </button>
        ))}
      </div>
      <div className="mt-2 flex items-center gap-2 text-[11px] text-zinc-400">
        <label>
          Results{' '}
          <input
            type="number"
            min={1}
            max={10}
            value={count}
            disabled={type === 'dialogue'}
            onChange={(e) => setCount(Math.min(10, Math.max(1, Number(e.target.value) || 1)))}
            aria-label="Result count"
            className="w-12 rounded-md border border-zinc-700 bg-zinc-900 px-1 py-1 text-xs text-zinc-100 disabled:opacity-40"
          />
        </label>
        <span>Model: {model}</span>
      </div>
      <button
        type="button"
        onClick={() => void run()}
        disabled={!prompt.trim() || generating}
        className="mt-2 w-full rounded-lg bg-gradient-to-r from-violet-600 to-cyan-500 px-3 py-2 text-xs font-semibold text-white disabled:opacity-50"
      >
        {generating ? 'Generating…' : 'Generate'}
      </button>
      {progress && <p className="mt-2 text-[11px] text-zinc-400">{progress}</p>}
      {error && <p className="mt-2 rounded-md border border-red-800 bg-red-950/40 p-2 text-[11px] text-red-200">{error}</p>}
      {results.length > 0 && (
        <ul className="mt-3 space-y-2">
          {results.map((r) => (
            <li key={`${r.kind}:${r.label}`} className="rounded-lg border border-zinc-800 bg-zinc-900 p-2">
              {r.kind === 'image' || r.kind === 'dialogue' ? (
                r.src ? (
                  <img src={r.src} alt={r.label} className="h-24 w-full rounded object-cover" />
                ) : (
                  <p className="text-xs text-zinc-500">No image — this browser could not render one.</p>
                )
              ) : r.kind === 'video' ? (
                <video src={r.src} className="h-24 w-full rounded object-cover" controls />
              ) : (
                <audio src={r.src} controls className="w-full" />
              )}
              <p className="mt-1.5 truncate text-xs font-medium" title={r.label}>{r.label}</p>
              <button
                type="button"
                className={`${addBtnCls} mt-1.5 w-full`}
                disabled={addedIds.has(`${r.kind}:${r.label}`)}
                onClick={() => addResult(r)}
              >
                {addedIds.has(`${r.kind}:${r.label}`) ? 'Added ✓' : '+ Add to timeline'}
              </button>
            </li>
          ))}
        </ul>
      )}
    </>
  );
}
