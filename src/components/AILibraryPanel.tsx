import { useProjectStore } from '../store/projectStore';
import {
  AI_CLIPS,
  AI_CLIP_SCENES,
  AI_IMAGES,
  AI_MUSIC_STYLES,
  AI_MUSIC_TRACKS,
  AI_SFX,
  AI_SFX_FAMILIES,
  aiFileAvailable,
  aiLibraryInstalled,
  aiMatches,
  renderAiTrackEntry,
  type AiClipEntry,
  type AiImageEntry,
  type AiMusicEntry,
  type AiSfxEntry,
} from '../lib/aiLibrary';
import { AI_VOICES, AI_VOICE_LANGUAGES, previewAiVoice, resolveAiVoice, type AiVoicePreset } from '../lib/voices';
import { voiceInfos, type TtsVoiceInfo } from '../lib/tts';
import {
  AI_GENERATE_TYPES,
  dialogueSceneFor,
  generateClip,
  generateImage,
  generateMusic,
  type AiGenerateType,
} from '../lib/aiGenerate';
import { playPreview, stopPreview } from '../lib/audio';
import { formatDuration } from '../lib/media';
