import { chromium } from 'playwright-core';
const EXE = '/home/hatch/.cache/ms-playwright/chromium_headless_shell-1254/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: EXE, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
await page.goto('http://127.0.0.1:5198/', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(1200);
const skip = page.getByRole('button', { name: /Skip tour/i });
if (await skip.count()) await skip.first().click();
const agree = page.getByRole('button', { name: 'Agree and continue' });
if (await agree.count()) await agree.click();
await page.waitForTimeout(300);
const okBtn = page.getByRole('button', { name: 'OK', exact: true });
if (await okBtn.count()) await okBtn.click();
await page.waitForTimeout(300);
await page.getByRole('button', { name: /Create project/ }).click();
await page.waitForTimeout(1000);
const txt = await page.evaluate(() => document.body.innerText.slice(0, 600));
console.log('AFTER BANNER CLICK, page text start:\n', txt);
console.log('Export button:', await page.getByRole('button', { name: 'Export' }).count());
console.log('Create-project banner still present:', await page.getByRole('button', { name: /Create project/ }).count());
await browser.close();
